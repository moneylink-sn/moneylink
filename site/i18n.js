export const I18n = {
  currentLang: 'fr',

  init() {
    const saved = localStorage.getItem('moneylink_lang');
    if (saved && (saved === 'fr' || saved === 'wo')) {
      this.currentLang = saved;
    } else {
      this.currentLang = 'fr';
    }
    this.applyToDOM();
  },

  setLanguage(lang) {
    if (lang !== 'fr' && lang !== 'wo') return;
    this.currentLang = lang;
    localStorage.setItem('moneylink_lang', lang);
    this.applyToDOM();
    
    // Déclenche un événement personnalisé pour notifier les composants dynamiques
    window.dispatchEvent(new CustomEvent('moneylink:languageChanged', { detail: { lang } }));
  },

  t(key, fallback = '') {
    const dict = translations[this.currentLang] || translations.fr;
    return dict[key] || translations.fr[key] || fallback || key;
  },

  applyToDOM() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.placeholder !== undefined) el.placeholder = text;
        } else {
          el.textContent = text;
        }
      }
    });

    // Mise à jour de l'indicateur de langue dans le sélecteur
    const langDisplay = document.getElementById('current-lang-text');
    if (langDisplay) {
      langDisplay.textContent = this.currentLang === 'wo' ? '🇸🇳 Wolof' : '🇫🇷 Français';
    }
  }
};

// Exposition globale pour usage dans app.js
if (typeof window !== 'undefined') {
  window.I18n = I18n;
  window.translations = translations;
}

export default I18n;
